"""Generate src/cpp/swat/out_ops.hpp: the arithmetic of SWAT+'s output types (the
`contains` functions of output_landscape_module, aquifer_module, sd_channel_module,
basin_module and channel_module behind operator(+), (/), (*) and (//)).

Each function becomes an inline C++ function with the Fortran name, field by field as
the Fortran writes it (fields it does not assign keep the type's default value, as a
Fortran function result of a type with default initialisation does), and the
operators of the module's interfaces call them; (//) becomes ``ave``.

    python tools/swat/ops2cpp.py <swatplus>/src
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MODULES = ["output_landscape_module", "aquifer_module", "sd_channel_module", "basin_module", "channel_module",
           "water_body_module"]
SKIP = {"chrc_mult", "print_prt_error"}  # in hyd_ops.hpp / not arithmetic
OUT = Path(__file__).resolve().parents[2] / "src" / "cpp" / "swat" / "out_ops.hpp"


def code_lines(text: str):
    """Statements without comments, continuation lines joined."""
    out, cur = [], ""
    for raw in text.splitlines():
        line = raw.split("!", 1)[0].rstrip()
        if not line.strip():
            continue
        if cur:
            line = line.lstrip().lstrip("&")
        if line.endswith("&"):
            cur += line[:-1] + " "
            continue
        out.append((cur + line).strip())
        cur = ""
    return out


NUM = re.compile(r"(?<![\w.])(\d+\.\d*|\d*\.\d+|\d+)([eE][+-]?\d+)?(?![\w.])")


def cexpr(e: str, args: dict) -> str:
    e = re.sub(r"\b(\w+)%(\w+)", lambda m: f"{m.group(1)}.{m.group(2)}", e)
    e = re.sub(r"\bconst\b", "k", e)

    def num(m):
        mant, ex = m.group(1), m.group(2) or ""
        if "." not in mant and not ex:
            return mant + ".0f"
        if mant.endswith("."):
            mant += "0"
        if mant.startswith("."):
            mant = "0" + mant
        return mant + ex + "f"

    return NUM.sub(num, e)


def parse(path: Path):
    lines = code_lines(path.read_text(errors="ignore"))
    try:
        start = next(i for i, l in enumerate(lines) if l.lower() == "contains")
    except StopIteration:
        return [], {}
    ops = {}
    for i, l in enumerate(lines[:start]):
        m = re.match(r"interface operator\s*\((\S+)\)", l, re.I)
        if m:
            p = re.match(r"module procedure\s+(\w+)", lines[i + 1], re.I)
            ops[p.group(1).lower()] = m.group(1)
    funcs, i = [], start + 1
    while i < len(lines):
        m = re.match(r"function\s+(\w+)\s*\(([^)]*)\)\s*result\s*\((\w+)\)", lines[i], re.I)
        if not m:
            i += 1
            continue
        name, args, res = m.group(1).lower(), [a.strip() for a in m.group(2).split(",")], m.group(3)
        types, body = {}, []
        i += 1
        if name in SKIP:
            while not re.match(r"end\s*function", lines[i], re.I):
                i += 1
            i += 1
            continue
        while not re.match(r"end\s*function", lines[i], re.I):
            l = lines[i]
            d = re.match(r"(type\s*\((\w+)\)|real|integer)\s*(,[^:]*)?::\s*(.+)", l, re.I)
            if d:
                t = d.group(2) or {"real": "float", "integer": "int"}[d.group(1).lower()]
                for v in d.group(4).split(","):
                    types[v.strip().split("=")[0].strip()] = t
            elif re.match(r"if\s*\((.+)\)\s*then$", l, re.I):
                body.append(("if", re.match(r"if\s*\((.+)\)\s*then$", l, re.I).group(1)))
            elif l.lower() == "else":
                body.append(("else", ""))
            elif re.match(r"end\s*if$", l, re.I):
                body.append(("end", ""))
            else:
                a = re.match(r"(\w+)%(\w+)\s*=\s*(.+)", l)
                if not a or a.group(1) != res:
                    raise SystemExit(f"{path.name} {name}: cannot translate `{l}`")
                body.append(("=", (a.group(2), a.group(3))))
            i += 1
        funcs.append((name, args, res, types, body))
        i += 1
    return funcs, ops


def main(src: str) -> None:
    out = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "//",
        "// GENERATED by tools/swat/ops2cpp.py from SWAT+ 62.0.1 (do not edit): the arithmetic of",
        "// the output types (" + ", ".join(MODULES) + "). Functions keep the",
        "// Fortran names; operator(//) is `ave`.",
        "",
        "#pragma once",
        "",
        '#include "swat/modules.hpp"',
        "",
        "namespace swat {",
        "",
    ]
    for mod in MODULES:
        funcs, ops = parse(Path(src) / f"{mod}.f90")
        out.append(f"// ---- {mod} " + "-" * max(0, 74 - len(mod)))
        for name, args, res, types, body in funcs:
            if name in SKIP:
                continue
            rt = types[res]
            params = []
            for a in args:
                t = types[a]
                params.append(f"float {'k' if a == 'const' else a}" if t == "float" else f"const {t}& {a}")
            out.append(f"inline {rt} {name}({', '.join(params)}) {{")
            out.append(f"    {rt} {res};")
            ind = "    "
            for kind, x in body:
                if kind == "=":
                    out.append(f"{ind}{res}.{x[0]} = {cexpr(x[1], types)};")
                elif kind == "if":
                    out.append(f"{ind}if ({cexpr(x, types)}) {{")
                    ind += "    "
                elif kind == "else":
                    out.append(f"{ind[:-4]}}} else {{")
                else:
                    ind = ind[:-4]
                    out.append(f"{ind}}}")
            out.append(f"    return {res};")
            out.append("}")
            op = ops.get(name)
            if op:
                call = ", ".join("k" if a == "const" else a for a in args)
                sig = ", ".join(params)
                fname = {"+": "operator+", "-": "operator-", "*": "operator*", "/": "operator/", "//": "ave"}[op]
                out.append(f"inline {rt} {fname}({sig}) {{ return {name}({call}); }}")
            out.append("")
    out.append("}  // namespace swat")
    OUT.write_text("\n".join(out) + "\n", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
