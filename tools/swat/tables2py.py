"""Generate src/landschaft/hydro/swat/_tables.py: the columns and units of the tables
SWAT+ prints (the *_header and *_header_units types of its output modules, as
src/cpp/swat/modules.hpp keeps them), for ls.hydro.swat's results.

    python tools/swat/tables2py.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODULES = ROOT / "src" / "cpp" / "swat" / "modules.hpp"
OUT = ROOT / "src" / "landschaft" / "hydro" / "swat" / "_tables.py"
KEYS = 7  # jday mon day yr unit gis_id name


def strs(text: str, name: str) -> list[str]:
    m = re.search(r"struct %s \{(.*?)\n\};" % name, text, re.S)
    return [s.strip() for s in re.findall(r'std::string \w+ = "(.*?)";', m.group(1))]


def main() -> None:
    text = MODULES.read_text()

    def table(head, units, extra=()):
        h, u = strs(text, head)[KEYS:], strs(text, units)[KEYS:]
        h = [c for c in h if c not in ("plant_cov", "mgt_ops")]
        return h, u[: len(h)]

    wb = table("output_waterbal_header", "output_waterbal_header_units")
    nb = table("output_nutbal_header", "output_nutbal_header_units")
    ls_h = [c for c in strs(text, "output_losses_header")[KEYS:] if c not in ("plant_cov", "mgt_ops")]
    ls_u = [u for c, u in zip(strs(text, "output_losses_header")[KEYS:], strs(text, "output_losses_header_units")[KEYS:])
            if c not in ("plant_cov", "mgt_ops")]
    pw = table("output_plantweather_header", "output_plantweather_header_units")
    aq = table("aqu_header", "aqu_header_units")
    hyd_u = strs(text, "hyd_header_units")[6:]
    wat_h, wat_u = strs(text, "ch_watbod_header")[KEYS:], strs(text, "ch_watbod_header_units")[KEYS:]
    ch_h, ch_u = list(wat_h), list(wat_u)
    for part in ("hyd_stor_header", "hyd_in_header", "hyd_out_header"):
        h = strs(text, part)
        suffix = h[0].split("_", 1)[1]
        ch_h += [c if c != "null" else f"temp_{suffix}" for c in h]
        ch_u += hyd_u[: len(h)]
    ch_h += strs(text, "wtmp_out_header")
    ch_u += strs(text, "wtmp_header_units")
    tables = {
        "hru_wb": (2000, "hru", wb),
        "hru_nb": (2020, "hru", nb),
        "hru_ls": (2030, "hru", (ls_h, ls_u)),
        "hru_pw": (2040, "hru", pw),
        "basin_wb": (2050, "basin", wb),
        "basin_nb": (2060, "basin", nb),
        "basin_ls": (2070, "basin", ([c for c in ls_h if c != "percn"], ls_u[: len(ls_h) - 1])),
        "basin_pw": (2080, "basin", pw),
        "channel_sd": (2500, "channel", (ch_h, ch_u)),
        "aquifer": (2520, "aquifer", aq),
    }
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        "# GENERATED by tools/swat/tables2py.py from the SWAT+ 62.0.1 output headers (do not edit).",
        '"""The tables SWAT+ prints: tag of the port\'s records (the Fortran unit of the daily',
        "table; + 1, 2, 3 for the monthly, yearly and average annual ones), the object each row",
        'is about, the column names and units as SWAT+ writes them in its headers."""',
        "",
        "TABLES = {",
    ]
    for name, (unit, obj, (cols, units)) in tables.items():
        assert len(cols) == len(units), name
        lines.append(f"    {name!r}: ({unit}, {obj!r}, {tuple(cols)!r},")
        lines.append(f"        {tuple(units)!r}),")
    lines += ["}", ""]
    OUT.write_text("\n".join(lines), newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
